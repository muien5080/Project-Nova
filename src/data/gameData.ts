export function getInitialGameState(): GameSaveData {
  const resources: Record<ResourceId, any> = {} as any;
  for (const def of RESOURCE_DEFS) {
    resources[def.id] = {
      amount: def.id === 'metal' ? 10 : def.id === 'wood' ? 10 : 0,
      capacity: def.baseCapacity,
      perSecond: 0,
      unlocked: def.unlockedByDefault,
    };
  }

  const buildings: Record<string, any> = {};
  for (const def of BUILDING_DEFS) {
    buildings[def.id] = {
      count: 0,
      enabled: true,
    };
  }

  const storageUpgrades: Record<string, any> = {};
  for (const def of STORAGE_DEFS) {
    storageUpgrades[def.id] = {
      count: 0,
    };
  }

  const techs: Record<string, any> = {};
  for (const def of TECH_DEFS) {
    techs[def.id] = {
      researched: false,
    };
  }

  const celestialBodies: Record<string, any> = {};
  for (const def of CELESTIAL_BODIES) {
    celestialBodies[def.id] = {
      explored: def.id === 'earth',
    };
  }

  const wonders: Record<string, any> = {};
  for (const def of WONDER_DEFS) {
    wonders[def.id] = {
      currentStage: 0,
    };
  }

  return {
    version: 1,
    resources,
    buildings,
    storageUpgrades,
    techs,
    celestialBodies,
    wonders,
    stats: {
      startTime: Date.now(),
      lastTickTime: Date.now(),
      totalTimePlayedMs: 0,
      manualClicks: 0,
      totalGathered: { metal: 10, wood: 10 },
      totalTechsResearched: 0,
      totalBuildingsConstructed: 0,
    },
    settings: {
      soundEnabled: true,
      buyMultiplier: 1,
      showStorageAlerts: true,
      activeTab: 'overview',
    },
    logs: [
      {
        id: 'init-1',
        timestamp: Date.now(),
        text: 'Project Nova telemetry initialized. Surface mining command active.',
        type: 'system',
      },
    ],
  };
}
